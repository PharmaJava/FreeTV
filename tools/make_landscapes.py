#!/usr/bin/env python3
"""Builds home/landscapes.js: the photos of FreeTV's own screensaver (Seville, Spain, Lithuania, nature).

The photos are Wikimedia Commons "featured" and "quality" pictures. Only files with a free licence (public domain, CC0, CC BY,
CC BY-SA) are kept, and each one carries its author and licence, which the screensaver shows in a corner (CC BY and CC BY-SA ask
for that). Run it again to refresh the list; it needs only curl, and goes slowly on purpose (Commons asks for that).

  python3 tools/make_landscapes.py
"""
import json, os, re, subprocess, sys, time, urllib.parse

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'home', 'landscapes.js')
# (category, place, most photos taken from it)
CATEGORIES = [
    ('Featured pictures of Seville', 'Sevilla', 20),
    ('Featured pictures of Andalusia', 'Andalucía', 20),
    ('Featured pictures of Spain', 'España', 20),
    ('Featured pictures of Lithuania', 'Lituania', 20),
    ('Featured pictures of Vilnius', 'Lituania', 20),
    ('Quality images of Seville', 'Sevilla', 14),
    ('Quality images of Lithuania', 'Lituania', 14),
    ('Quality images of Andalusia', 'Andalucía', 10),
    ('Quality images of the Curonian Spit', 'Lituania', 10),
    ('Quality images of Aukštaitija National Park', 'Lituania', 8),
    ('Quality images of Doñana National Park', 'España', 10),
    ('Quality images of Sierra Nevada (Spain)', 'España', 10),
    ('Landscapes of Lithuania', 'Lituania', 14),
    ('Lakes of Lithuania', 'Lituania', 10),
    ('Forests of Lithuania', 'Lituania', 8),
    ('Landscapes of Andalusia', 'Andalucía', 10),
    ('Parque de María Luisa', 'Sevilla', 10),
    ('Guadalquivir River in Seville', 'Sevilla', 8),
    ('Plaza de España (Seville)', 'Sevilla', 8),
    ('Landscapes of Spain', 'España', 10),
]
FREE = re.compile(r'^(public domain|pd\b|cc0|cc[- ]by(-sa)?\b)', re.I)


def api(**p):
    p['format'] = 'json'
    url = 'https://commons.wikimedia.org/w/api.php?' + urllib.parse.urlencode(p)
    for attempt in range(5):
        out = subprocess.run(['curl', '-sS', '-m', '40', '-A', 'FreeTV-landscapes/1.0 (github.com/PharmaJava/FreeTV)', url],
                             capture_output=True).stdout
        try:
            return json.loads(out)
        except ValueError:
            time.sleep(4 * (attempt + 1))
    return {}


def plain(html):
    return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', html or '')).strip()


def main():
    seen, photos = set(), []
    for cat, place, limit in CATEGORIES:
        members = api(action='query', list='categorymembers', cmtitle='Category:' + cat, cmtype='file', cmlimit=500)
        titles = [m['title'] for m in members.get('query', {}).get('categorymembers', []) if re.search(r'\.jpe?g$', m['title'], re.I)]
        kept = 0
        for i in range(0, len(titles), 40):
            if kept >= limit:
                break
            time.sleep(1.5)
            r = api(action='query', titles='|'.join(titles[i:i + 40]), prop='imageinfo', iiprop='size|extmetadata',
                    iiextmetadatafilter='LicenseShortName|Artist|ImageDescription')
            for page in r.get('query', {}).get('pages', {}).values():
                if kept >= limit:
                    break
                info = (page.get('imageinfo') or [{}])[0]
                meta = info.get('extmetadata') or {}
                lic = plain((meta.get('LicenseShortName') or {}).get('value'))
                w, h = info.get('width', 0), info.get('height', 0)
                if not FREE.match(lic) or w < 2400 or h <= 0 or w / float(h) < 1.4 or page['title'] in seen:
                    continue
                seen.add(page['title'])
                artist = plain((meta.get('Artist') or {}).get('value'))[:60] or 'Wikimedia Commons'
                photos.append([page['title'][len('File:'):], place, artist, lic])
                kept += 1
        print('%-48s %2d of %d' % (cat, kept, len(titles)), file=sys.stderr)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* Generated by tools/make_landscapes.py: [file on Wikimedia Commons, place, author, licence]. */\n')
        f.write('var LANDSCAPES = ' + json.dumps(photos, ensure_ascii=False, indent=0).replace('\n', '') .replace('],[', '],\n[') + ';\n')
    print('%d photos -> %s' % (len(photos), os.path.normpath(OUT)), file=sys.stderr)


main()
