#!/usr/bin/env python3
"""Builds FreeTV's home app (the files the TV runs) into out/home.

    python3 tools/build_home.py              # reads config.properties (made from the example if it isn't there)
    python3 tools/build_home.py --config other.properties

Only Python 3 is needed. The result is a plain folder of web files; install.sh puts it in the helper's launcher/ folder
and the helper's own scripts pack and install it. Plain ES5 JavaScript and CSS, as the TV runs Chrome 79 at best and
some older LG TVs much older.
"""
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kids_channels  # noqa: E402  (the Custom tab's shortcuts)
OUT = os.path.join(ROOT, 'out', 'home')


def community_host(value):
    """The computer that installs community apps for the TV ("192.168.1.20" or "192.168.1.20:8777"), or ''."""
    if value and not re.match(r'^\d{1,3}(\.\d{1,3}){3}(:\d{2,5})?$', value):
        sys.exit('config.properties: community_host must be an address like 192.168.1.20 (got "%s")' % value)
    return value


def read_config(path):
    if not os.path.exists(path):
        shutil.copy(os.path.join(ROOT, 'config.example.properties'), path)
        print('Created %s from the example: edit your city (and your TMDB key, if you want the picks) and build again.'
              % os.path.basename(path))
    values = {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#') or '=' not in line:
                continue
            key, value = line.split('=', 1)
            values[key.strip()] = value.strip().strip('"')

    def number(key, default):
        v = values.get(key, '') or default
        if not re.match(r'^-?\d+(\.\d+)?$', v):
            sys.exit('config.properties: %s must be a number (got "%s")' % (key, v))
        return v

    return {
        'tmdbKey': values.get('tmdb_key', ''),
        'tmdbRegion': values.get('tmdb_region', 'ES') or 'ES',
        'latitude': number('latitude', '40.4168'),
        'longitude': number('longitude', '-3.7038'),
        'city': values.get('city', ''),
        'language': values.get('language', 'auto') or 'auto',
        'currency': values.get('currency', 'USD') or 'USD',
        'temperature': values.get('temperature', 'auto') or 'auto',
        'showCrypto': values.get('show_crypto', 'true').lower() != 'false',
        'hideAnimation': values.get('hide_animation', 'false').lower() == 'true',
        'channels': kids_channels.for_build(values.get('kids_channels', '')),
        'communityHost': community_host(values.get('community_host', '')),
        'hideServices': [s.strip().lower() for s in values.get('hide_services', '').split(',') if s.strip()],
    }


LG_ONLY = ['renewal.js', 'extras.js', 'extras.css', 'helper-control.js', 'native-bootstrap.js', 'appinfo.json', 'splash.png']


def files(config, tizen=False):
    """The app's files, {path inside the app: bytes}. tizen=True leaves out what only makes sense on LG (the Home button
    helper's pieces and the Developer Mode renewal) and adds the logos Samsung's apps need."""
    out = {}
    home = os.path.join(ROOT, 'home')
    for name in sorted(os.listdir(home)):
        if tizen and name in LG_ONLY:
            continue
        with open(os.path.join(home, name), 'rb') as f:
            out[name] = f.read()
    for folder in ('symbols', 'fonts', 'tiles') + (('samsung-icons',) if tizen else ()):
        base = os.path.join(ROOT, 'assets', folder)
        for name in sorted(os.listdir(base)):
            with open(os.path.join(base, name), 'rb') as f:
                out[('icons' if folder == 'samsung-icons' else folder) + '/' + name] = f.read()
    for c in config.get('channels', []):
        if c.get('thumb'):   # the cover pictures kids_channels.py saved on this computer
            with open(os.path.join(kids_channels.WORK, c['thumb'].split('/', 1)[1]), 'rb') as f:
                out[c['thumb']] = f.read()
    try:
        version = json.loads(out['appinfo.json'].decode('utf-8'))['version']
    except (KeyError, ValueError):
        version = ''
    out['config.js'] = ('/* Generated by tools/build_home.py from config.properties. */\nwindow.CONFIG = %s;\n'
                        % json.dumps(dict(config, version=version), ensure_ascii=False)).encode('utf-8')
    out['apps.js'] = (b"/* Replaced by the helper's installer with the apps it reads from your TV. */\n"
                      b"window.TV_APPS = {apps: [], inputs: []};\n")
    if tizen:
        page = out['index.html'].decode('utf-8').replace('\r\n', '\n')
        for tag in ('<link rel="stylesheet" href="extras.css">', '<script src="renewal.js"></script>', '<script src="extras.js"></script>',
                    '<script src="helper-control.js"></script>', '<script src="native-bootstrap.js"></script>', '<script src="apps.js"></script>'):
            page = page.replace(tag + '\n', '')
        out['index.html'] = page.encode('utf-8')
        del out['apps.js']
    return out


def write(app, out_dir):
    if os.path.isdir(out_dir):
        shutil.rmtree(out_dir)
    for path, content in sorted(app.items()):
        target = os.path.join(out_dir, path)
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with open(target, 'wb') as f:
            f.write(content)


def config_path(args):
    return os.path.abspath(args[args.index('--config') + 1]) if '--config' in args else os.path.join(ROOT, 'config.properties')


def build(config):
    app = files(config)
    write(app, OUT)
    print('Home built in out/home (%d files)' % len(app))
    if not config['tmdbKey']:
        print('No TMDB key: the film and series picks stay off (everything else works).')


if __name__ == '__main__':
    build(read_config(config_path(sys.argv[1:])))
