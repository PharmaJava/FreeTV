#!/usr/bin/env python3
"""Builds FreeTV's home app (the files the TV runs) into out/home.

    python3 tools/build_home.py              # reads config.properties (made from the example if it isn't there)
    python3 tools/build_home.py --config other.properties

Only Python 3 is needed. The result is a plain folder of web files; install.sh puts it in the helper's launcher/ folder
and the helper's own scripts pack and install it. Plain ES5 JavaScript and CSS, as the TV runs Chrome 79 at best and
some older LG TVs much older.
"""
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'out', 'home')


def read_config(path):
    if not os.path.exists(path):
        shutil.copy(os.path.join(ROOT, 'config.example.properties'), path)
        print('Created %s from the example: edit your city (and your TMDB key, if you want the picks) and build again.'
              % os.path.basename(path))
    values = {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#') or '=' not in line:
                continue
            key, value = line.split('=', 1)
            values[key.strip()] = value.strip().strip('"')

    def number(key, default):
        v = values.get(key, '') or default
        if not re.match(r'^-?\d+(\.\d+)?$', v):
            sys.exit('config.properties: %s must be a number (got "%s")' % (key, v))
        return v

    return {
        'tmdbKey': values.get('tmdb_key', ''),
        'tmdbRegion': values.get('tmdb_region', 'ES') or 'ES',
        'latitude': number('latitude', '40.4168'),
        'longitude': number('longitude', '-3.7038'),
        'city': values.get('city', ''),
        'language': values.get('language', 'auto') or 'auto',
        'currency': values.get('currency', 'USD') or 'USD',
        'temperature': values.get('temperature', 'auto') or 'auto',
        'showCrypto': values.get('show_crypto', 'true').lower() != 'false',
        'hideAnimation': values.get('hide_animation', 'false').lower() == 'true',
        'hideServices': [s.strip().lower() for s in values.get('hide_services', '').split(',') if s.strip()],
    }


def build(config):
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)
    home = os.path.join(ROOT, 'home')
    for name in sorted(os.listdir(home)):
        shutil.copy(os.path.join(home, name), os.path.join(OUT, name))
    for folder in ('symbols', 'fonts'):
        shutil.copytree(os.path.join(ROOT, 'assets', folder), os.path.join(OUT, folder))
    with open(os.path.join(OUT, 'config.js'), 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/build_home.py from config.properties. */\nwindow.CONFIG = %s;\n'
                % json.dumps(config, ensure_ascii=False))
    with open(os.path.join(OUT, 'apps.js'), 'w', encoding='utf-8') as f:
        f.write('/* Replaced by the helper\'s installer with the apps it reads from your TV. */\n'
                'window.TV_APPS = {apps: [], inputs: []};\n')
    print('Home built in out/home (%d files)' % sum(len(files) for _, _, files in os.walk(OUT)))
    if not config['tmdbKey']:
        print('No TMDB key: the film and series picks stay off (everything else works).')


if __name__ == '__main__':
    args = sys.argv[1:]
    path = os.path.abspath(args[args.index('--config') + 1]) if '--config' in args else os.path.join(ROOT, 'config.properties')
    build(read_config(path))
